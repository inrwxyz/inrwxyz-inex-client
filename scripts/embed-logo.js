/**
 * Embeds src/inex-logo.png into src/logo-default.js (base64) so the launcher logo can NEVER disappear.
 * - PNG present  -> embedded copy is refreshed (so replacing the PNG updates the logo).
 * - PNG deleted  -> the previously embedded copy is kept and keeps being used.
 * Runs automatically before `npm start` and before every build.
 */
const fs = require('fs');
const path = require('path');

const png = path.join(__dirname, '..', 'src', 'inex-logo.png');
const out = path.join(__dirname, '..', 'src', 'logo-default.js');

if (!fs.existsSync(png)) {
  console.log(fs.existsSync(out)
    ? '[embed-logo] inex-logo.png not found - keeping the already embedded logo.'
    : '[embed-logo] No inex-logo.png and no embedded logo yet.');
  process.exit(0);
}
const b64 = fs.readFileSync(png).toString('base64');
fs.writeFileSync(out, `/* AUTO-GENERATED by scripts/embed-logo.js - do not edit */\nwindow.INEX_DEFAULT_LOGO = 'data:image/png;base64,${b64}';\n`, 'utf8');
console.log('[embed-logo] Embedded inex-logo.png into src/logo-default.js');
