#!/usr/bin/env node
// Generates dist-ui/tauri-bridge.js (the Tauri replacement of preload.js) from preload.js, so the
// window.inexAPI surface can never drift from the Electron one. Runs from scripts/build-ui.js.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const preload = fs.readFileSync(path.join(root, 'preload.js'), 'utf8');

const m = preload.match(/exposeInMainWorld\(\s*['"]inexAPI['"]\s*,\s*\{([\s\S]*)\}\s*\)\s*;?\s*$/);
if (!m) { console.error('gen-bridge: could not find the inexAPI object in preload.js'); process.exit(1); }

const body = m[1]
  .replace(/ipcRenderer\.invoke\(/g, 'invoke(')
  .replace(/ipcRenderer\.on\(/g, 'on(');

if (/ipcRenderer/.test(body)) { console.error('gen-bridge: unsupported ipcRenderer usage left in preload.js'); process.exit(1); }

const out = `/* AUTO-GENERATED by scripts/gen-bridge.js from preload.js — do not edit by hand. */
(function () {
  'use strict';
  var T = window.__TAURI__;
  if (!T) { console.error('[INEX] Tauri API not available (withGlobalTauri must be true).'); return; }
  var tauriInvoke = T.core.invoke;

  // ---- ipcRenderer replacement ----
  function invoke(channel) {
    var args = Array.prototype.slice.call(arguments, 1);
    // Tauri rejects with plain strings; the UI code expects Error objects (err.message), like Electron gave.
    return tauriInvoke('inex_invoke', { channel: channel, args: args }).catch(function (e) {
      throw (e instanceof Error) ? e : new Error(String(e));
    });
  }
  var listeners = {};
  function on(channel, handler) {
    (listeners[channel] = listeners[channel] || []).push(handler);
  }
  T.event.listen('inex-event', function (e) {
    var p = e.payload || {};
    var list = listeners[p.channel];
    if (!list) return;
    for (var i = 0; i < list.length; i++) {
      try { list[i](null, p.data); } catch (err) { console.error(err); }
    }
  });

  var api = {${body}};

  // ---- things that are handled natively in the window instead of the Node backend ----
  var win = T.window.getCurrentWindow();
  api.minimizeWindow = function () { return win.minimize(); };
  api.maximizeWindow = function () { return win.toggleMaximize(); };
  api.writeClipboardText = function (text) {
    text = String(text == null ? '' : text);
    var fallback = function () {
      var ta = document.createElement('textarea');
      ta.value = text; ta.style.position = 'fixed'; ta.style.opacity = '0';
      document.body.appendChild(ta); ta.select();
      try { document.execCommand('copy'); } catch (_) {}
      ta.remove();
    };
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(text).catch(function () { fallback(); });
    }
    fallback();
    return Promise.resolve();
  };

  window.inexAPI = api;

  // ---- frameless window: -webkit-app-region (Electron) => startDragging (Tauri) ----
  document.addEventListener('mousedown', function (ev) {
    if (ev.button !== 0) return;
    for (var el = ev.target; el && el.nodeType === 1; el = el.parentElement) {
      var v = getComputedStyle(el).getPropertyValue('-webkit-app-region');
      if (v === 'no-drag') return;
      if (v === 'drag') {
        if (ev.detail === 2) win.toggleMaximize(); else win.startDragging();
        return;
      }
    }
  });

  // show the window once the page is painted (window is created hidden to avoid a white flash)
  var shown = false;
  function showWin() { if (shown) return; shown = true; win.show().then(function () { return win.setFocus(); }).catch(function () {}); }
  if (document.readyState === 'complete') showWin(); else window.addEventListener('load', showWin);
  setTimeout(showWin, 3000);
})();
`;
fs.mkdirSync(path.join(root, 'dist-ui'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist-ui', 'tauri-bridge.js'), out);
console.log('gen-bridge: wrote dist-ui/tauri-bridge.js');
